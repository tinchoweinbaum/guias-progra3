public abstract class Cofre {
    public Cofre() {
        super();
    }

    public abstract void abiertoPorGuerrero(Guerrero g);

    public abstract void abiertoPorArquero(Arquero a);

    public abstract void abiertoPorCaballero(Caballero c);

    public abstract void abiertoPorDragon(Dragon d);
}
